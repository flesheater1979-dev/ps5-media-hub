#!/usr/bin/env python3
"""Generate projects/evoplayer/media/src/evo_charset_tables.inc.

Code-page tables for evo_charset.c, which turns a non-UTF-8 subtitle file into
UTF-8 (#128): Windows-1250..1257 and 874 (single byte, upper half only), and
GBK (cp936), Big5 (cp950), Shift-JIS (cp932) and EUC-KR (cp949) (two byte).

Re-run only to change which code pages are covered:
    python3 -X utf8 tools/gen_charset_tables.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "projects", "evoplayer", "media", "src", "evo_charset_tables.inc")

SINGLE = [1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 874]
# name, python codec, lead range, trail range
DOUBLE = [
    ("gbk", "cp936", 0x81, 0xFE, 0x40, 0xFE),
    ("big5", "cp950", 0x81, 0xFE, 0x40, 0xFE),
    ("sjis", "cp932", 0x81, 0xFC, 0x40, 0xFC),
    ("euckr", "cp949", 0x81, 0xFE, 0x41, 0xFE),
]


def single(cp):
    row = []
    for b in range(0x80, 0x100):
        try:
            ch = bytes([b]).decode("cp%d" % cp)
            row.append(ord(ch[0]))
        except UnicodeDecodeError:
            row.append(0xFFFD)
    return row


def double(codec, lead_lo, lead_hi, trail_lo, trail_hi):
    rows = []
    for lead in range(lead_lo, lead_hi + 1):
        for trail in range(trail_lo, trail_hi + 1):
            try:
                ch = bytes([lead, trail]).decode(codec)
                v = ord(ch) if len(ch) == 1 else 0
            except UnicodeDecodeError:
                v = 0
            rows.append(v if v < 0x10000 else 0)
    return rows


def emit(f, name, values, per_line=12):
    f.write("static const unsigned short %s[%d] = {\n" % (name, len(values)))
    for i in range(0, len(values), per_line):
        f.write("    " + ", ".join("0x%04X" % v for v in values[i:i + per_line]) + ",\n")
    f.write("};\n\n")


with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* Generated by tools/gen_charset_tables.py - do not edit. */\n\n")
    for cp in SINGLE:
        emit(f, "evo_cs_cp%d" % cp, single(cp))
    for name, codec, ll, lh, tl, th in DOUBLE:
        emit(f, "evo_cs_%s" % name, double(codec, ll, lh, tl, th))
print("wrote", OUT, os.path.getsize(OUT), "bytes")
